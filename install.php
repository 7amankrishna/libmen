/**
 * install.php — one-time setup wizard.
 *
 *   1. Enter the MySQL credentials from your InfinityFree hPanel
 *      (MySQL Databases) — they are written to config/database.php.
 *      (Skip this step if you already edited config/database.php manually.)
 *   2. The database tables are created automatically (schema.sql, no data).
 *   3. Create your first staff (admin) account.
 *
 * DELETE THIS FILE after installation for security.
 */
require_once __DIR__ . '/includes/bootstrap.php';

$configPath = __DIR__ . '/config/database.php';
$cfg = db_config();

function run_schema(PDO $pdo): void {
    $sql = file_get_contents(__DIR__ . '/database/schema.sql');
    $buf = '';
    $count = 0;
    foreach (preg_split('/\r?\n/', $sql) as $line) {
        $t = trim($line);
        if ($t === '' || strpos($t, '--') === 0) continue;
        $buf .= $line . "\n";
        if (substr($t, -1) === ';') {
            $pdo->exec($buf);
            $count++;
            $buf = '';
        }
    }
    if (trim($buf) !== '') { $pdo->exec($buf); $count++; }
    if ($count === 0) throw new RuntimeException('schema.sql contained no statements');
}

function tables_ready(PDO $pdo): bool {
    $t = $pdo->query("SHOW TABLES LIKE 'users'")->fetchColumn();
    return $t !== false;
}

$error = null;
$info  = null;

/* ---- step 1: save DB credentials -------------------------------------- */
if (($_POST['step'] ?? '') === 'db') {
    csrf_verify();
    $new = [
        'host' => trim($_POST['host'] ?? ''),
        'port' => trim($_POST['port'] ?? '3306') ?: '3306',
        'name' => trim($_POST['name'] ?? ''),
        'user' => trim($_POST['user'] ?? ''),
        'pass' => (string)($_POST['pass'] ?? ''),
    ];
    if ($new['host'] === '' || $new['name'] === '' || $new['user'] === '') {
        $error = 'Host, database name and username are required.';
        $cfg = array_merge($cfg, $new);
    } else {
        try {
            db_try($new); // validate credentials BEFORE writing the file
            $code = "<?php\n/** Generated by install.php — keep this file secret (it is blocked by .htaccess). */\nreturn "
                . var_export($new, true) . ";\n";
            $written = @file_put_contents($configPath, $code);
            if ($written === false) {
                $error = 'Connected OK, but config/database.php is not writable by PHP. Paste this into the file manually via FTP/File Manager:';
                $info = $code;
            } else {
                @chmod($configPath, 0644);
                redirect('install.php?done=db');
            }
        } catch (PDOException $e) {
            $error = 'Could not connect with these credentials: ' . $e->getMessage();
            $cfg = array_merge($cfg, $new);
        }
    }
}

/* ---- step 3: create the first admin ------------------------------------ */
if (($_POST['step'] ?? '') === 'admin') {
    csrf_verify();
    $name  = trim($_POST['name'] ?? '');
    $email = trim($_POST['email'] ?? '');
    $pass  = (string)($_POST['pass'] ?? '');
    $pass2 = (string)($_POST['pass2'] ?? '');
    if ($name === '' || !filter_var($email, FILTER_VALIDATE_EMAIL) || strlen($pass) < 6) {
        $error = 'Enter a name, a valid email and a password of at least 6 characters.';
    } elseif ($pass !== $pass2) {
        $error = 'The two passwords do not match.';
    } else {
        $pdo = db();
        $st = $pdo->prepare('INSERT INTO users (name, email, password_hash, role) VALUES (?,?,?,?)');
        $st->execute([$name, $email, password_hash($pass, PASSWORD_DEFAULT), 'admin']);
        log_activity('install.admin_created', $email);
        redirect('install.php?done=admin');
    }
}

/* ---- figure out current state ------------------------------------------ */
$connected = false;
$ready = false;
$hasAdmin = false;
$pdo = null;
try {
    $pdo = db_try();
    $connected = true;
    if (!tables_ready($pdo)) {
        run_schema($pdo);          // safe: every statement is IF NOT EXISTS
        $info = $info ?? 'Database tables created successfully (empty — no dummy data).';
    }
    $ready = tables_ready($pdo);
    if ($ready) {
        $hasAdmin = ((int)$pdo->query('SELECT COUNT(*) FROM users')->fetchColumn()) > 0;
    }
} catch (PDOException $e) {
    $error = $error ?? 'Not connected yet: ' . $e->getMessage();
}

